    private void loadGolonganDarah() {
        try {
            String sql = "SHOW COLUMNS FROM pasien LIKE 'goldar'";
            Connection kon = koneksi.koneksiDb();
            PreparedStatement pst = kon.prepareStatement(sql);
            ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                String enumStr = rs.getString("Type"); // enum('A','B','AB','O')
                enumStr = enumStr.replace("enum(", "").replace(")", "").replace("'", "");
                String[] values = enumStr.split(",");

                Goldar.removeAllItems();
                for (String value : values) {
                    Goldar.addItem(value);
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal load ENUM: " + e.getMessage());
        }
    }
    
