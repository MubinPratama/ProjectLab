    private void tampilkanData() {
    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("ID Pasien");
    model.addColumn("Nama");
    model.addColumn("Alamat");
    model.addColumn("Jenis Kelamin");
    model.addColumn("Telepon");
    model.addColumn("Tanggal Lahir");
    model.addColumn("Tinggi Badan");
    model.addColumn("Berat Badan");
    model.addColumn("Gol. Darah");

    try {
        String sql = "SELECT * FROM pasien";
        Connection kon = koneksi.koneksiDb();
        Statement stm = kon.createStatement();
        ResultSet res = stm.executeQuery(sql);

        while (res.next()) {
            model.addRow(new Object[]{
                res.getString("No_rm"),
                res.getString("Nama"),
                res.getString("Alamat"),
                res.getString("jk"),
                res.getString("no_telp"),
                res.getString("Tgl_lahir"),
                res.getDouble("Tinggi"),
                res.getDouble("Berat"),
                res.getString("goldar")
            });
        }

        tabel_pasien.setModel(model);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal menampilkan data: " + e.getMessage());
    }
    
    
}
    
    public void generateIdPasien() {
    try {
        Connection kon = koneksi.koneksiDb();
        String sql = "SELECT MAX(RIGHT(No_rm, 3)) FROM pasien";
        PreparedStatement pst = kon.prepareStatement(sql);
        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            int id = rs.getString(1) != null ? Integer.parseInt(rs.getString(1)) + 1 : 1;
            String kode = String.format("%03d", id); // hasil: PS001, PS002
            IdPasien.setText(kode);
        } else {
            IdPasien.setText("001");
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Gagal generate ID: " + e.getMessage());
    }
}

