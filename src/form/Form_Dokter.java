    private void bt_hapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bt_hapusActionPerformed
        // TODO add your handling code here:                                       
    int selectedRow = tabel_dokter.getSelectedRow();
    
    if (selectedRow != -1) {
        int idDokter = Integer.parseInt(tabel_dokter.getValueAt(selectedRow, 0).toString());

        int konfirmasi = JOptionPane.showConfirmDialog(null, 
            "Yakin ingin menghapus data ini?", "Konfirmasi", 
            JOptionPane.YES_NO_OPTION);

        if (konfirmasi == JOptionPane.YES_OPTION) {
            try {
                Connection kon = koneksi.koneksiDb();
                String sql = "DELETE FROM dokter WHERE id_Dokter = ?";
                PreparedStatement pst = kon.prepareStatement(sql);
                pst.setInt(1, idDokter);
                pst.executeUpdate();

                DefaultTableModel model = (DefaultTableModel) tabel_dokter.getModel();
                model.removeRow(selectedRow);

                JOptionPane.showMessageDialog(null, "Data berhasil dihapus.");
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(null, "Terjadi kesalahan: " + ex.getMessage());
            }
        }
    } else {
        JOptionPane.showMessageDialog(null, "Pilih data terlebih dahulu!");
    }
    }//GEN-LAST:event_bt_hapusActionPerformed

